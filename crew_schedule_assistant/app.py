def weekly_profiles(connection):
    stored=connection.execute('''SELECT c.id,c.name,c.active,a.weekday,a.source_label
        FROM crew c JOIN crew_weekly_availability a ON c.id=a.crew_id
        ORDER BY c.name,a.weekday''').fetchall()
    profiles={}
    for item in stored:
        profile=profiles.setdefault(item['id'],{'name':item['name'],'active':item['active'],'days':['Not recorded']*7})
        profile['days'][item['weekday']]=item['source_label']
    return list(profiles.values())


def init_db():
    schema = [
        """CREATE TABLE IF NOT EXISTS crew (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL UNIQUE,
            role TEXT NOT NULL DEFAULT 'Crew',
            active INTEGER NOT NULL DEFAULT 1
        )""",
        """CREATE TABLE IF NOT EXISTS shifts (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            crew_id INTEGER NOT NULL REFERENCES crew(id),
            day TEXT NOT NULL,
            note TEXT DEFAULT '',
            UNIQUE(crew_id, day)
        )""",
        """CREATE TABLE IF NOT EXISTS requests (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            crew_id INTEGER REFERENCES crew(id),
            requester_name TEXT NOT NULL,
            kind TEXT NOT NULL,
            day TEXT NOT NULL,
            reason TEXT NOT NULL,
            target_id INTEGER REFERENCES crew(id),
            status TEXT NOT NULL DEFAULT 'Pending',
            created_at TEXT NOT NULL
        )""",
        """CREATE TABLE IF NOT EXISTS uploads (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            filename TEXT NOT NULL,
            original_name TEXT NOT NULL,
            uploaded_at TEXT NOT NULL
        )""",
        """CREATE TABLE IF NOT EXISTS admins (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE,
            password_hash TEXT NOT NULL
        )""",
        """CREATE TABLE IF NOT EXISTS crew_weekly_availability (
            crew_id INTEGER NOT NULL REFERENCES crew(id),
            weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
            periods TEXT[] NOT NULL CHECK (periods <@ ARRAY['OPENER','MID','CLOSER','GY']::TEXT[]),
            source_label TEXT NOT NULL,
            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (crew_id, weekday)
        )""",
        """CREATE TABLE IF NOT EXISTS admin_availability_drafts (
            admin_id INTEGER PRIMARY KEY REFERENCES admins(id),
            csv_text TEXT NOT NULL CHECK (octet_length(csv_text) <= 128000),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
    ]
    with db() as c:
        for statement in schema:
            c.execute(statement)
        # Optional time ranges preserve existing date-only requests.
        c.execute('ALTER TABLE requests ADD COLUMN IF NOT EXISTS start_time TEXT')
        c.execute('ALTER TABLE requests ADD COLUMN IF NOT EXISTS end_time TEXT')
        c.execute('ALTER TABLE requests ADD COLUMN IF NOT EXISTS shift_period TEXT')
        c.execute('ALTER TABLE requests ADD COLUMN IF NOT EXISTS weekdays INTEGER[] CHECK (weekdays <@ ARRAY[0,1,2,3,4,5,6])')
        c.execute('ALTER TABLE requests ALTER COLUMN day DROP NOT NULL')
        # Upgrade earlier PostgreSQL databases in place without removing requests.
        c.execute('ALTER TABLE requests ADD COLUMN IF NOT EXISTS requester_name TEXT')
        c.execute('ALTER TABLE requests ALTER COLUMN crew_id DROP NOT NULL')
        c.execute("""UPDATE requests r SET requester_name = crew.name
                     FROM crew WHERE r.crew_id = crew.id AND r.requester_name IS NULL""")
        if not c.execute('SELECT id FROM admins LIMIT 1').fetchone():
            password = os.environ.get('ADMIN_PASSWORD')
            if not password:
                raise RuntimeError('ADMIN_PASSWORD must be set before first startup.')
            username = os.environ.get('ADMIN_USERNAME', 'admin')
            c.execute('INSERT INTO admins(username,password_hash) VALUES (%s,%s)',
                      (username, generate_password_hash(password)))


init_db()

def login_required(f):
    @wraps(f)
    def wrapper(*args,**kwargs):
        if not session.get('admin'): return redirect(url_for('login'))
        return f(*args,**kwargs)
    return wrapper

def valid_times(start, end):
    try:
        start_time = datetime.strptime(start, '%H:%M').time()
        end_time = datetime.strptime(end, '%H:%M').time()
        return start_time != end_time
    except (ValueError, TypeError):
        return False

def iso_day(v):
    try:return date.fromisoformat(v).isoformat()
    except (ValueError,TypeError): return None

def crew_streak(connection,crew_id,day):
    """Consecutive assigned calendar days ending on day, including a proposed shift on day."""
    target=date.fromisoformat(day)
    count=1; prior=target-timedelta(days=1)
    days={r['day'] for r in connection.execute('SELECT day FROM shifts WHERE crew_id=%s AND day<=%s',(crew_id,day))}
    while prior.isoformat() in days:
        count+=1;prior-=timedelta(days=1)
    return count

def recommendations(connection,day):
    busy={x['crew_id'] for x in connection.execute('SELECT crew_id FROM shifts WHERE day=%s',(day,))}
    excluded={x['crew_id'] for x in connection.execute("SELECT crew_id FROM requests WHERE day=%s AND kind='Request Off' AND status='Approved'",(day,))}
    results=[]
    weekly={r['crew_id']:r for r in connection.execute(
        'SELECT crew_id,periods,source_label FROM crew_weekly_availability WHERE weekday=%s',
        (date.fromisoformat(day).weekday(),))}
    for c in connection.execute('SELECT * FROM crew WHERE active=1 ORDER BY name'):
        if c['id'] in busy or c['id'] in excluded:continue
        availability=weekly.get(c['id'])
        if availability is not None and not availability['periods']:continue
        streak=crew_streak(connection,c['id'],day)
        results.append({'id':c['id'],'name':c['name'],'role':c['role'],'new_streak':streak,'safe':streak<=5,
                        'availability':availability['source_label'] if availability else 'Not recorded — verify availability'})
    return sorted(results,key=lambda r:(not r['safe'],r['new_streak'],r['name']))

