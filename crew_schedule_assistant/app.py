@app.route('/admin/manage-crew',methods=['GET','POST'])
@login_required
def weekly():
    csrf=session.setdefault('weekly_csrf',secrets.token_urlsafe(32))
    signer=URLSafeTimedSerializer(app.secret_key,salt='weekly-import-v1')
    rows=[]; token=None; errors=[]
    draft=BASE/'data'/'crew-weekly-draft.csv'
    csv_text=draft.read_text(encoding='utf-8') if draft.exists() else 'name,mon,tue,wed,thu,fri,sat,sun\n'
    if request.method=='GET':
        with db() as c:
            stored_draft=c.execute('SELECT csv_text FROM admin_availability_drafts WHERE admin_id=%s',(session['admin'],)).fetchone()
        if stored_draft:csv_text=stored_draft['csv_text']
        if csv_text.strip() not in ('','name,mon,tue,wed,thu,fri,sat,sun'):
            try:
                rows=parse_csv(csv_text)
            except ValueError:
                errors.append('The saved draft could not be opened. Your saved data is unchanged.')
    if request.method=='POST':
        if not secrets.compare_digest(request.form.get('csrf',''),csrf):abort(400)
        csv_text=request.form.get('csv_text','')
        try:
            if request.form.get('action')=='stage_grid':
                csv_text=csv_from_grid(request.form,include_all=True)
                rows=parse_csv(csv_text)
                with db() as c:
                    c.execute('''INSERT INTO admin_availability_drafts(admin_id,csv_text) VALUES (%s,%s)
                        ON CONFLICT(admin_id) DO UPDATE SET csv_text=EXCLUDED.csv_text,updated_at=CURRENT_TIMESTAMP''',
                        (session['admin'],csv_text))
                flash('Draft edits saved. Confirmed Time Arrangement has not changed.','success')
                return redirect(url_for('weekly'))
            if request.form.get('action')=='stage':
                rows=parse_csv(csv_text)
                with db() as c:
                    c.execute('''INSERT INTO admin_availability_drafts(admin_id,csv_text) VALUES (%s,%s)
                        ON CONFLICT(admin_id) DO UPDATE SET csv_text=EXCLUDED.csv_text,updated_at=CURRENT_TIMESTAMP''',
                        (session['admin'],csv_text))
                flash(f'Saved {len(rows)} crew entries as an unverified review draft. No active crew or weekly profiles were created.','success')
                return redirect(url_for('weekly'))
            if request.form.get('action')=='save':
                if request.form.get('reviewed')!='yes':
                    raise ValueError('Confirm you have checked every name and day against the source.')
                payload=signer.loads(request.form.get('token',''),max_age=3600)
                if payload.get('admin')!=session['admin'] or payload.get('csrf')!=csrf:abort(400)
                csv_text=payload['csv']
                rows=parse_csv(csv_text)
                with db() as c:
                    created=save_rows(c,rows)
                flash(f'Confirmed weekly availability for {len(rows)} crew; created {created} new crew.','success')
                return redirect(url_for('dashboard',section='ta'))
            if request.form.get('action')=='review_grid':
                csv_text=csv_from_grid(request.form)
            rows=parse_csv(csv_text)
            if any(r['errors'] for r in rows):
                errors.append('Correct the flagged entries below, then preview again. Use Save draft to keep unfinished edits.')
            else:
                token=signer.dumps({'csv':csv_text,'admin':session['admin'],'csrf':csrf})
        except (BadSignature,SignatureExpired):
            errors.append('Preview expired or changed. Preview the CSV again before saving.')
        except (ValueError,UniqueViolation) as e:
            errors.append(str(e) if isinstance(e,ValueError) else 'A crew name already exists. Check the roster and preview again.')
    with db() as c:
        people=c.execute('SELECT * FROM crew ORDER BY name').fetchall()
    return render_template('weekly.html',section='crew',selected_day=date.today().isoformat(),
                           csrf=csrf,csv_text=csv_text,rows=rows,token=token,errors=errors,
                           people=people,days=DAYS,labels=LABELS)

