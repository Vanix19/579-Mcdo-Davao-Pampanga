@app.post('/admin/shift')
@login_required
def add_shift():
    day=iso_day(request.form.get('day'))
    try:cid=int(request.form.get('crew_id',''))
    except ValueError:cid=0
    if not day:flash('Please select a valid date.','error');return redirect(url_for('dashboard'))
    with db() as c:
        person=c.execute('SELECT * FROM crew WHERE id=%s AND active=1',(cid,)).fetchone()
        off=c.execute("SELECT 1 FROM requests WHERE crew_id=%s AND day=%s AND kind='Request Off' AND status='Approved'",(cid,day)).fetchone()
        if not person or off:flash('Crew is inactive, missing, or approved for leave.','error')
        else:
            try:
                c.execute('INSERT INTO shifts(crew_id,day,note) VALUES (%s,%s,%s)',(cid,day,''))
                streak=crew_streak(c,cid,day)
                flash(f'Shift added. {person["name"]} reaches day {streak} consecutively.' if streak>=6 else 'Shift added.','warning' if streak>=6 else 'success')
            except UniqueViolation:
                c.rollback()
                flash('Crew is already scheduled for this date.','error')
    return redirect(url_for('dashboard',day=day))

