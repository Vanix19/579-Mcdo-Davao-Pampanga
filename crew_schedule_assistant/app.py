@app.post('/admin/upload')
@login_required
def upload():
    f=request.files.get('photo')
    if not f or not f.filename:flash('Choose a schedule image.','error');return redirect(url_for('dashboard'))
    ext=Path(secure_filename(f.filename)).suffix.lower()
    if ext not in ('.jpg','.jpeg','.png','.webp'):
        flash('Only JPG, PNG, or WEBP images are allowed.','error');return redirect(url_for('dashboard'))
    filename=uuid.uuid4().hex+ext
    f.save(UPLOAD/filename)
    with db() as c:c.execute('INSERT INTO uploads(filename,original_name,uploaded_at) VALUES (%s,%s,%s)',(filename,secure_filename(f.filename),datetime.now().isoformat(timespec='minutes')))
    flash('Schedule image uploaded. Enter its shifts using Add Shift so day-count checks can work.','success')
    return redirect(url_for('dashboard'))

